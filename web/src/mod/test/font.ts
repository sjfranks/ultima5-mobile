/** Eight full rows, drawn in dots: '#' set. */
function rows(...lines: string[]): number[] {
  return lines.map((l) => [...l.padEnd(8)].reduce((v, c, i) => (c === '#' ? v | (0x80 >> i) : v), 0));
}

