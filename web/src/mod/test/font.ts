const SUN = rows('#  ##  #', ' # ## # ', '  ####  ', '########', '########', '  ####  ', ' # ## # ', '#  ##  #');

function face(withMoons: boolean): Uint8Array {
  const out = new Uint8Array(1024);
  for (const [c, r] of Object.entries(LETTERS)) {
    const code = c.charCodeAt(0);
    r.forEach((bits, y) => {
      out[code * 8 + y] = (bits << 2) & 0xff;
    });
  }
  // '{', '|' and '}' are the frame's in the game's face; the letters have no use for them.
  for (const [code, r] of Object.entries(PICTURES)) out.set(r, Number(code) * 8);
  if (withMoons) {
    MOONS.forEach((r, i) => out.set(r, (0x30 + i) * 8));
    out.set(SUN, 0x2a * 8);
  }
  return out;
}

/** IBM.CH: the letters, the little pictures and the frame. */
export const ibmFont = (): Uint8Array => face(false);
/** RUNES.CH: the same letters (Test has no runes), the moons and the sun. */
export const runesFont = (): Uint8Array => face(true);
